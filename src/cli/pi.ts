/**
 * pi's side of `n2n-nexus install pi`: the extension that carries the hook
 * events, and where it lives. pi has no hook configuration file, so the
 * extension is the hook: `~/.pi/agent/extensions/n2n-nexus.ts`, which pi loads
 * on start and reloads with /reload. It runs `"<node>" "<entry>" hook pi`
 * (with --client-pid, the pi process, and --endpoint when install was given
 * one) for each event, as the Claude Code and Codex hooks do, and starts the
 * background wait (`hook pi --wait --session <id>`) after each turn: a wake the
 * wait prints on stderr (exit code 2) is sent to pi as the user's next message.
 *
 * Node built-ins only: this module is loaded by the installer and by doctor.
 */
import fs from "node:fs";
import path from "node:path";

import { piAgentDir } from "./client-dirs.js";

/** The first line of the generated file; uninstall and doctor recognise our extension by it. */
export const PI_EXTENSION_MARK = "// n2n-nexus: generated by \"n2n-nexus install pi\"; removed by \"n2n-nexus uninstall pi\".";

/** The extension file pi loads: `<pi agent dir>/extensions/n2n-nexus.ts`. */
export const piExtensionFile = (): string => path.join(piAgentDir(), "extensions", "n2n-nexus.ts");

/** What the generated extension runs: the Node path, the entry script and the --endpoint install was given. */
export type PiExtensionCommand = { node: string; entry: string; endpoint?: string };

/** The extension source for `command`; its constants are the only install-specific part. */
export function renderPiExtension({ node, entry, endpoint }: PiExtensionCommand): string {
    return `${PI_EXTENSION_MARK}
import { spawn, type ChildProcess } from "node:child_process";
import type { ExtensionAPI } from "@earendil-works/pi-coding-agent";

const NODE = ${JSON.stringify(node)};
const ENTRY = ${JSON.stringify(entry)};
const ENDPOINT: string | null = ${JSON.stringify(endpoint ?? null)};
const CUSTOM_TYPE = "n2n-nexus";
/** Longest a non-blocking hook may hold a pi step; the Stop hook may hold longer on purpose. */
const HOOK_TIMEOUT_MS = 15000;
/** The session end must finish before pi exits. */
const SESSION_END_TIMEOUT_MS = 1500;
/** How long the session end waits for a Stop still under way, which must reach the host first. */
const STOP_GRACE_MS = 1000;

type Result = { code: number | null; stdout: string; stderr: string };

function run(args: string[], input: Record<string, unknown> | undefined, timeoutMs?: number, started?: (child: ChildProcess) => void): Promise<Result> {
    return new Promise((resolve) => {
        let child: ChildProcess;
        try {
            child = spawn(NODE, [ENTRY, ...args], { stdio: ["pipe", "pipe", "pipe"], windowsHide: true });
        } catch {
            resolve({ code: null, stdout: "", stderr: "" });
            return;
        }
        started?.(child);
        let stdout = "";
        let stderr = "";
        const timer = timeoutMs === undefined ? undefined : setTimeout(() => child.kill(), timeoutMs);
        child.stdout.on("data", (chunk) => (stdout += chunk));
        child.stderr.on("data", (chunk) => (stderr += chunk));
        child.on("error", () => resolve({ code: null, stdout, stderr }));
        child.on("exit", (code) => {
            if (timer) clearTimeout(timer);
            resolve({ code, stdout, stderr });
        });
        child.stdin.on("error", () => { /* the hook exited before reading its input */ });
        if (input !== undefined) child.stdin.end(JSON.stringify(input));
        else child.stdin.end();
    });
}

/** The hook command: this client, the pi process, and the endpoint install was given. */
function hookArgs(...extra: string[]): string[] {
    return ["hook", "pi", "--client-pid", String(process.pid), ...(ENDPOINT ? ["--endpoint", ENDPOINT] : []), ...extra];
}

/** The text a hook adds to the conversation (its hookSpecificOutput.additionalContext), or "". */
function contextOf(result: Result): string {
    try {
        const out = JSON.parse(result.stdout.trim() || "null");
        const text = out?.hookSpecificOutput?.additionalContext;
        return typeof text === "string" ? text : "";
    } catch {
        return "";
    }
}

export default function (pi: ExtensionAPI) {
    let sessionId = "";
    let cwd = "";
    let alive = true;
    let wait: ChildProcess | undefined;
    /** A later turn ended while the previous wait was still finishing or retrying. */
    let restartWait = false;
    /** The Stop hook under way, if any: the session end waits for it, or ends it. */
    let stopping: { child?: ChildProcess; done: Promise<unknown> } | undefined;
    /**
     * The run under way was continued by the Stop hook: it is the same turn, so its start is no
     * prompt of the user's (that would reset the automatic-turn count), and its Stop says so
     * (stop_hook_active), as Claude Code's does.
     */
    let continued = false;

    const event = (name: string, extra: Record<string, unknown> = {}) => ({ hook_event_name: name, session_id: sessionId, cwd, ...extra });

    /** Start the background wait for this session; a wake it prints is sent to pi as the next user message. */
    function startWait(): void {
        if (wait) {
            restartWait = true;
            return;
        }
        restartWait = false;
        let child: ChildProcess;
        try {
            child = spawn(NODE, [ENTRY, ...hookArgs("--wait", "--session", sessionId)], { stdio: ["ignore", "ignore", "pipe"], windowsHide: true });
        } catch {
            return;
        }
        let stderr = "";
        child.stderr.on("data", (chunk) => (stderr += chunk));
        child.on("error", () => { if (wait === child) wait = undefined; });
        child.on("close", (code) => {
            if (wait !== child) return;
            wait = undefined;
            // Exit code 2: the wait handed over a wake (its text is on stderr); anything else is nothing to deliver.
            if (code === 2 && stderr.trim()) pi.sendUserMessage(stderr.replace(/\\s+$/, ""), { deliverAs: "followUp" });
            if (restartWait) startWait();
        });
        wait = child;
    }

    function stopWait(): void {
        restartWait = false;
        const child = wait;
        wait = undefined;
        child?.kill();
    }

    /** After a run ends: the Stop hook continues the run when messages wait for this session; otherwise the wait starts. */
    async function settle(): Promise<void> {
        const current: { child?: ChildProcess; done: Promise<unknown> } = { done: Promise.resolve() };
        const done = run(hookArgs(), event("Stop", { stop_hook_active: continued }), undefined, (child) => (current.child = child));
        continued = false;
        current.done = done;
        stopping = current;
        const result = await done;
        if (stopping === current) stopping = undefined;
        if (!alive) return;
        let reason = "";
        try {
            const out = JSON.parse(result.stdout.trim() || "null");
            if (out?.decision === "block" && typeof out.reason === "string") reason = out.reason;
        } catch {
            // no output: nothing waits for this session
        }
        if (reason) {
            continued = true;
            pi.sendUserMessage(reason, { deliverAs: "followUp" });
        } else {
            startWait();
        }
    }

    pi.on("session_start", async (startEvent, ctx) => {
        stopWait();
        sessionId = ctx.sessionManager.getSessionId() ?? "";
        cwd = ctx.cwd;
        alive = true;
        continued = false;
        if (!sessionId) return;
        const result = await run(hookArgs(), event("SessionStart", { source: startEvent.reason }), HOOK_TIMEOUT_MS);
        const text = contextOf(result);
        if (text) pi.sendMessage({ customType: CUSTOM_TYPE, content: text, display: false }, { deliverAs: "nextTurn" });
    });

    pi.on("before_agent_start", async (startEvent) => {
        if (!sessionId || startEvent.messageType !== "user") return;
        // The host ends a pending wait on this hook. A wake already in its pipe must
        // finish delivery, even if this run ends before the pipe closes.
        restartWait = false;
        if (continued) return;
        const result = await run(hookArgs(), event("UserPromptSubmit"), HOOK_TIMEOUT_MS);
        const text = contextOf(result);
        if (text) return { message: { customType: CUSTOM_TYPE, content: text, display: false } };
    });

    pi.on("tool_result", async (toolEvent) => {
        // A call another tool made (codemode running an MCP tool, pi's default for them) is skipped: its result
        // reaches the model only as far as the script returns it, so the announcement goes with the result of
        // the call the model made, which follows.
        if (!sessionId || toolEvent.isError || toolEvent.parentToolCallId) return;
        const result = await run(hookArgs(), event("PostToolUse", { tool_name: toolEvent.toolName, tool_use_id: toolEvent.toolCallId }), HOOK_TIMEOUT_MS);
        const text = contextOf(result);
        if (text) return { content: [...toolEvent.content, { type: "text", text }] };
    });

    pi.on("agent_settled", (settled) => {
        // A run the user aborted is not continued (Claude Code runs no Stop hook on an interrupt either),
        // and the next run is the user's own.
        if (settled.aborted) continued = false;
        if (!sessionId || settled.aborted) return;
        void settle();
    });

    pi.on("session_shutdown", async (shutdown) => {
        alive = false;
        stopWait();
        const pending = stopping;
        // /reload goes on with the same session: the reloaded extension reports it at its session_start. A Stop
        // still holding is ended (its answer would reach no one), so the host keeps what it would have announced.
        if (shutdown.reason === "reload") {
            pending?.child?.kill();
            return;
        }
        // pi often ends right after a run (pi -p): the Stop of that run must not reach the host after the session end.
        if (pending) {
            await Promise.race([pending.done, new Promise((resolve) => setTimeout(resolve, STOP_GRACE_MS))]);
            pending.child?.kill();
        }
        if (!sessionId) return;
        await run(hookArgs(), event("SessionEnd", { reason: shutdown.reason }), SESSION_END_TIMEOUT_MS);
        sessionId = "";
    });
}
`;
}

/** The command the extension runs, read back from a generated file; undefined when the file is not ours. */
export function readPiExtension(text: string): PiExtensionCommand | undefined {
    if (!text.startsWith(PI_EXTENSION_MARK)) return undefined;
    const constant = (name: string): string | undefined => {
        const m = new RegExp(`^const ${name}(?:: [^=]+)? = (.+);$`, "m").exec(text);
        if (!m) return undefined;
        try {
            const value: unknown = JSON.parse(m[1]);
            return typeof value === "string" ? value : undefined;
        } catch {
            return undefined;
        }
    };
    const node = constant("NODE");
    const entry = constant("ENTRY");
    if (node === undefined || entry === undefined) return undefined;
    const endpoint = constant("ENDPOINT");
    return { node, entry, ...(endpoint ? { endpoint } : {}) };
}

/** Write the extension atomically (a file, not a symlink target: a link is followed as the config files are). */
export function writePiExtension(file: string, text: string): void {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    const tmp = `${file}.${process.pid}.tmp`;
    fs.writeFileSync(tmp, text);
    try {
        fs.renameSync(tmp, file);
    } catch (error) {
        fs.rmSync(tmp, { force: true });
        throw error;
    }
}

/** Read the extension file: its text, or undefined when there is none. */
export function readPiExtensionFile(file: string): string | undefined {
    try {
        return fs.readFileSync(file, "utf8");
    } catch (error) {
        if ((error as NodeJS.ErrnoException).code === "ENOENT") return undefined;
        throw error;
    }
}
